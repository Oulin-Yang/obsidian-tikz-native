'use strict';
// Inline our renderer so installation needs only Obsidian's usual three files.
const fs = require('node:fs');
const path = require('node:path');
const root = __dirname;
const translations = fs.readFileSync(path.join(root, 'i18n.js'), 'utf8');
const renderer = fs.readFileSync(path.join(root, 'renderer.js'), 'utf8')
  .replace("require('./i18n.js')", 'i18n');
const theming = fs.readFileSync(path.join(root, 'theming.js'), 'utf8');
const plugin = fs.readFileSync(path.join(root, 'src/plugin.js'), 'utf8')
  .replace("require(path.join(__dirname, 'renderer.js'))", 'requireRenderer()')
  .replace("require(path.join(__dirname, 'theming.js'))", 'requireTheming()')
  .replace("require(path.join(__dirname, 'i18n.js'))", 'i18n');
const bundled = '// Generated by node build.js.\n' +
  'const i18n = (() => { const module = { exports: {} };\n' + translations + '\nreturn module.exports; })();\n' +
  'function requireTheming() { const module = { exports: {} };\n' + theming + '\nreturn module.exports; }\n' +
  'function requireRenderer() { const module = { exports: {} };\n' + renderer + '\nreturn module.exports; }\n' + plugin;
fs.writeFileSync(path.join(root, 'main.js'), bundled);
